export function statusText(forecast, today) {
  if (!forecast.last) {
    return `هنوز تاریخی ننوشته‌ایم. روزی که عادت ماهانه‌ات شروع شد «ثبت شروع» را بزن. از روی همان تاریخ‌های خودت، ماه‌های بعد را می‌گویم.\n${CARE}`;
  }
  const { stats, next, lateDays } = forecast;
  const lines = [
    `آخرین شروع: ${formatDual(forecast.last)}`,
    stats.usedDefaultCycle
      ? "فاصله را فعلاً ۲۸ روز گرفته‌ام، چون هنوز دو شروعِ قابل‌حساب نداریم. این یکی تقریبی است و با تاریخ‌های خودت عوض می‌شود."
      : `فاصله‌ی میانگین: ${toFaDigits(stats.cycleLen)} روز، از روی ${toFaDigits(stats.gaps.length)} فاصله‌ی ثبت‌شده‌ی خودت.`,
  ];
  if (forecast.rolled) lines.push("چند دوره از آخرین ثبت گذشته؛ این تاریخ را با همان فاصله جلو آوردم.");
  if (lateDays > 0) {
    lines.push(`شروعِ حساب‌شده ${formatDual(next)} بود و ${toFaDigits(lateDays)} روز از آن گذشته. عجله نکن؛ خواب، سفر و خستگی تاریخ را جابه‌جا می‌کنند.`);
  } else {
    lines.push(`شروع بعدی، حدود ${formatDual(next)}.`);
  }
  if (stats.skipped.length) lines.push("یک فاصله‌ی خیلی کوتاه یا خیلی بلند را در میانگین نیاوردم تا حساب به‌هم نریزد.");
  lines.push(pick(STATUS_CLOSE, today || next));
  lines.push(CARE);
  return lines.join("\n");
}

