function norm(value) {
  return String(value)
    .replace(/[۰-۹]/g, (digit) => String("۰۱۲۳۴۵۶۷۸۹".indexOf(digit)))
    .replace(/ي/g, "ی")
    .replace(/ك/g, "ک")
    .replace(/\s+/g, "")
    .toLowerCase();
}

export function searchKnowledge(query) {
  const clean = norm(query);
  if (!clean) return null;
  const found = ARTICLES.find((article) => article.keys.some((key) => clean.includes(norm(key)) || norm(key).includes(clean)));
  if (!found) return null;
  return `${found.title}\n${found.body}`;
}

